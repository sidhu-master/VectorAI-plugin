import { readFile } from 'node:fs/promises';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const defaultRepositoryRoot = () => resolve(fileURLToPath(new URL('..', import.meta.url)));

export const DSH_BUNDLE_DIRECTORIES = [
  'plugin-dsh-space',
  'plugin-dsh-annotation',
];

export const DSH_BUILD_INPUT_DIRECTORIES = [
  'plugin-dsh-space-client',
  'plugin-dsh-space-host',
  'plugin-dsh-annotation-client',
  'plugin-dsh-annotation-host',
];

export function assertDshRuntimeManifest(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error('DSH_RUNTIME_MANIFEST_INVALID');
  }
  const { version, tag, commit, registrySdkVersion, profile, bundleRuntimeDependencies } = value;
  for (const [key, member] of Object.entries({ version, tag, commit, registrySdkVersion, profile })) {
    if (typeof member !== 'string' || member.length === 0) {
      throw new Error(`DSH_RUNTIME_MANIFEST_FIELD_INVALID:${key}`);
    }
  }
  if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/u.test(version)) {
    throw new Error('DSH_RUNTIME_MANIFEST_VERSION_INVALID');
  }
  if (tag !== `dsh-v${version}`) throw new Error('DSH_RUNTIME_MANIFEST_TAG_MISMATCH');
  if (!/^[a-f0-9]{40}$/u.test(commit)) throw new Error('DSH_RUNTIME_MANIFEST_COMMIT_INVALID');
  if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/u.test(registrySdkVersion)) {
    throw new Error('DSH_RUNTIME_MANIFEST_SDK_VERSION_INVALID');
  }
  if (!bundleRuntimeDependencies || typeof bundleRuntimeDependencies !== 'object'
    || Array.isArray(bundleRuntimeDependencies)) {
    throw new Error('DSH_RUNTIME_MANIFEST_BUNDLE_DEPENDENCIES_INVALID');
  }
  const normalizedDependencies = {};
  for (const [bundle, dependencies] of Object.entries(bundleRuntimeDependencies)) {
    if (!Array.isArray(dependencies) || dependencies.length === 0) {
      throw new Error(`DSH_RUNTIME_MANIFEST_BUNDLE_DEPENDENCIES_INVALID:${bundle}`);
    }
    const normalized = [...dependencies];
    if (normalized.some((name) => typeof name !== 'string'
      || !name.startsWith('@deepseek-ai/dsh-')
      || name === '@deepseek-ai/cordis')) {
      throw new Error(`DSH_RUNTIME_MANIFEST_BUNDLE_DEPENDENCY_INVALID:${bundle}`);
    }
    const sorted = [...new Set(normalized)].sort();
    if (JSON.stringify(normalized) !== JSON.stringify(sorted)) {
      throw new Error(`DSH_RUNTIME_MANIFEST_BUNDLE_DEPENDENCIES_UNSORTED:${bundle}`);
    }
    normalizedDependencies[bundle] = sorted;
  }
  return {
    version, tag, commit, registrySdkVersion, profile,
    bundleRuntimeDependencies: normalizedDependencies,
  };
}

export function readDshRuntimeManifest(root = defaultRepositoryRoot()) {
  const release = JSON.parse(readFileSync(resolve(root, 'release/dsh-plugins.json'), 'utf8'));
  return assertDshRuntimeManifest(release.dsh);
}

export function formatDshRuntimeCoordinates(baseline) {
  return `${baseline.version}\n${baseline.tag}\n${baseline.commit}\n`;
}

export function renderDshTypeScriptBaseline(baseline) {
  return `// SPDX-License-Identifier: Apache-2.0
// Generated by scripts/sync-dsh-runtime-baseline.mjs. Do not edit directly.

export const DSH_RUNTIME_VERSION = ${JSON.stringify(baseline.version)} as const;
export const DSH_RUNTIME_TAG = ${JSON.stringify(baseline.tag)} as const;
export const DSH_RUNTIME_COMMIT = ${JSON.stringify(baseline.commit)} as const;
`;
}

export function renderDshSwiftBaseline(baseline) {
  return `// SPDX-License-Identifier: Apache-2.0
// Generated by scripts/sync-dsh-runtime-baseline.mjs. Do not edit directly.

enum DSHRuntimeBaseline {
    static let version = ${JSON.stringify(baseline.version)}
    static let tag = ${JSON.stringify(baseline.tag)}
    static let commit = ${JSON.stringify(baseline.commit)}
}
`;
}

export async function inspectDshRuntimeDrift(root = defaultRepositoryRoot()) {
  const baseline = await readDshRuntimeManifest(root);
  const drift = [];
  const generated = [
    [
      'packages/plugin-dsh-annotation-host/src/dsh-runtime-baseline.generated.ts',
      renderDshTypeScriptBaseline(baseline),
    ],
    [
      'apps/dsh-launcher-macos/Sources/DSHRuntimeBaseline.generated.swift',
      renderDshSwiftBaseline(baseline),
    ],
  ];
  for (const [path, expected] of generated) {
    const actual = await readOptional(resolve(root, path));
    if (actual !== expected) drift.push(`${path}:generated-content`);
  }

  for (const directory of DSH_BUNDLE_DIRECTORIES) {
    const path = `packages/${directory}/package.json`;
    const manifest = JSON.parse(await readFile(resolve(root, path), 'utf8'));
    for (const [name, version] of Object.entries(manifest.peerDependencies ?? {})) {
      if (!name.startsWith('@deepseek-ai/dsh-')) continue;
      if (version !== baseline.version) drift.push(`${path}:peerDependencies.${name}`);
      if (manifest.peerDependenciesMeta?.[name]?.optional !== true) {
        drift.push(`${path}:peerDependenciesMeta.${name}`);
      }
    }
  }

  for (const directory of DSH_BUILD_INPUT_DIRECTORIES) {
    const path = `packages/${directory}/package.json`;
    const manifest = JSON.parse(await readFile(resolve(root, path), 'utf8'));
    for (const [name, version] of Object.entries(manifest.dependencies ?? {})) {
      if (name.startsWith('@deepseek-ai/dsh-') && version !== baseline.registrySdkVersion) {
        drift.push(`${path}:dependencies.${name}`);
      }
    }
  }
  const rootManifest = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));
  for (const [name, version] of Object.entries(rootManifest.devDependencies ?? {})) {
    if (name.startsWith('@deepseek-ai/dsh-') && version !== baseline.registrySdkVersion) {
      drift.push(`package.json:devDependencies.${name}`);
    }
  }
  return drift.sort();
}

async function readOptional(path) {
  try {
    return await readFile(path, 'utf8');
  } catch (error) {
    if (error?.code === 'ENOENT') return undefined;
    throw error;
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.stdout.write(formatDshRuntimeCoordinates(readDshRuntimeManifest()));
}
