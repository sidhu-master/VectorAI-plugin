import { randomUUID } from 'node:crypto';
import { spawn } from 'node:child_process';
import { access, mkdir, readFile, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import {
  checkDshBuildFreshness,
  defaultRepositoryRoot,
} from './dsh-build-freshness.mjs';
import { readDshRuntimeManifest } from './dsh-runtime-manifest.mjs';

const SUPPORTED_VERSION = readDshRuntimeManifest().version;
const PROBE_MARKER = 'ADAPTER_RUNTIME_OK';
const PROBE_PROMPT = `Set value to exactly ${PROBE_MARKER}.`;
const PROBE_PERSONA = 'Return only the requested structured result.';
const HASH_PATTERN = /^sha256:[a-f0-9]{64}$/;
const FORBIDDEN_RECORD_KEYS = new Set(['prompt', 'persona', 'messages', 'system']);

export function createProbePluginSource({ bundleUrl }) {
  if (typeof bundleUrl !== 'string' || !bundleUrl.startsWith('file:')) {
    throw new Error('DSH_RECOGNITION_PROBE_BUNDLE_URL_INVALID');
  }
  return `// Generated by scripts/probe-dsh-recognition-runtime.mjs
import { appendFileSync } from 'node:fs';
import { createDshRecognitionModelAdapter } from ${JSON.stringify(bundleUrl)};

export const name = 'vectorai-recognition-adapter-probe';

function record(type, payload) {
  const output = process.env.VECTORAI_DSH_RECOGNITION_PROBE_OUTPUT;
  if (!output) throw new Error('VECTORAI_DSH_RECOGNITION_PROBE_OUTPUT_REQUIRED');
  appendFileSync(output, \`${'${JSON.stringify({ type, ...payload })}'}\\n\`, 'utf8');
}

export function apply(ctx) {
  const adapter = createDshRecognitionModelAdapter(ctx);
  let started = false;
  record('adapter/runtime', adapter.runtimeReport());
  ctx.on('agent/request', async ({ agent, signal }, next) => {
    const config = await next();
    if (started) return config;
    started = true;
    const result = await adapter.review({
      pipelineId: 'runtime-probe',
      pipelineVersion: '1',
      parentSessionId: String(agent.id),
      prompt: [{ type: 'text', text: ${JSON.stringify(PROBE_PROMPT)} }],
      outputSchema: {
        type: 'object',
        additionalProperties: false,
        required: ['value'],
        properties: { value: { type: 'string', enum: [${JSON.stringify(PROBE_MARKER)}] } },
      },
      persona: ${JSON.stringify(PROBE_PERSONA)},
      maxDepth: 1,
      maxTokens: 256,
      timeoutMs: 60_000,
      signal,
    });
    record('adapter/result', result);
    return config;
  }, { global: true });
}

export const inject = ['agents', 'attachments', 'llm', 'subagents'];
`;
}

export function validateProbeRecords(records) {
  if (!Array.isArray(records) || records.length !== 2) {
    throw new Error('DSH_RECOGNITION_PROBE_RECORD_COUNT_INVALID');
  }
  assertSanitized(records);
  const runtime = records.find(({ type }) => type === 'adapter/runtime');
  const result = records.find(({ type }) => type === 'adapter/result');
  if (!runtime || !result) throw new Error('DSH_RECOGNITION_PROBE_RECORD_TYPES_INVALID');
  if (runtime.supportedVersion !== SUPPORTED_VERSION || runtime.compatible !== true) {
    throw new Error('DSH_RECOGNITION_PROBE_RUNTIME_INCOMPATIBLE');
  }
  assertVersions(runtime.versions);
  if (result.stopReason !== 'completed' || result.structured?.value !== PROBE_MARKER) {
    throw new Error('DSH_RECOGNITION_PROBE_RESULT_INVALID');
  }
  if (!Array.isArray(result.observations) || result.observations.length === 0) {
    throw new Error('DSH_RECOGNITION_PROBE_OBSERVATION_MISSING');
  }
  for (const observation of result.observations) assertObservation(observation);
  const first = result.observations[0];
  return {
    compatible: true,
    versions: structuredClone(runtime.versions),
    provider: first.provider,
    model: first.model,
    ...(typeof first.reasoningEffort === 'string' ? { reasoningEffort: first.reasoningEffort } : {}),
    observationCount: result.observations.length,
  };
}

export function formatProbeSummary(summary) {
  const reasoningEffort = summary.reasoningEffort ?? 'default';
  return [
    'recognition probe: pass',
    `compatible=${String(summary.compatible)}`,
    `versions agent=${summary.versions.agent} llm=${summary.versions.llm} subagent=${summary.versions.subagent}`,
    `provider=${summary.provider} model=${summary.model} reasoningEffort=${reasoningEffort} observations=${summary.observationCount}`,
    '',
  ].join('\n');
}

export async function runDshRecognitionProbe({
  root = defaultRepositoryRoot(),
  dshCli = process.env.VECTORAI_DSH_CLI,
  timeoutMs = 90_000,
} = {}) {
  const repositoryRoot = resolve(root);
  const freshness = await checkDshBuildFreshness({ root: repositoryRoot, target: 'annotation' });
  if (!freshness.fresh) {
    throw new Error(`DSH_RECOGNITION_PROBE_BUNDLE_STALE:${freshness.reason}`);
  }
  const bundlePath = join(repositoryRoot, 'packages/plugin-dsh-annotation/lib/index.js');
  await access(bundlePath);
  const cliPath = resolve(dshCli ?? join(homedir(), '.dsh/profiles/node_modules/@deepseek-ai/dsh/lib/bin.js'));
  await access(cliPath);

  const runDirectory = join(
    repositoryRoot,
    '.local/dsh-recognition-probe',
    `${new Date().toISOString().replaceAll(':', '-')}-${randomUUID()}`,
  );
  await mkdir(runDirectory, { recursive: true });
  const pluginPath = join(runDirectory, 'adapter-probe.mjs');
  const patchPath = join(runDirectory, 'adapter-probe.patch.yml');
  const outputPath = join(runDirectory, 'events.jsonl');
  await writeFile(pluginPath, createProbePluginSource({ bundleUrl: pathToFileURL(bundlePath).href }), 'utf8');
  await writeFile(patchPath, "- insert:\n    - id: vectorai-recognition-adapter-probe\n      name: './adapter-probe.mjs'\n", 'utf8');

  const exit = await spawnProbe({ cliPath, patchPath, outputPath, runDirectory, timeoutMs });
  if (exit.timedOut) throw new Error('DSH_RECOGNITION_PROBE_TIMEOUT');
  if (exit.code !== 0) throw new Error(`DSH_RECOGNITION_PROBE_PROCESS_FAILED:${String(exit.code)}`);
  const records = parseJsonLines(await readFile(outputPath, 'utf8'));
  return validateProbeRecords(records);
}

function assertObservation(observation) {
  if (typeof observation?.provider !== 'string' || observation.provider.length === 0
    || typeof observation.model !== 'string' || observation.model.length === 0
    || !Number.isSafeInteger(observation.messageCount) || observation.messageCount < 1
    || !Array.isArray(observation.toolNames) || !observation.toolNames.includes('structured_output')
    || !HASH_PATTERN.test(observation.requestDigest)
    || !HASH_PATTERN.test(observation.systemDigest)) {
    throw new Error('DSH_RECOGNITION_PROBE_OBSERVATION_INVALID');
  }
  assertVersions(observation.runtimeVersions);
}

function assertVersions(versions) {
  if (!versions || versions.agent !== SUPPORTED_VERSION
    || versions.llm !== SUPPORTED_VERSION
    || versions.subagent !== SUPPORTED_VERSION) {
    throw new Error('DSH_RECOGNITION_PROBE_VERSION_MISMATCH');
  }
}

function assertSanitized(records) {
  const serialized = JSON.stringify(records);
  if (serialized.includes(PROBE_PROMPT) || serialized.includes(PROBE_PERSONA)) {
    throw new Error('DSH_RECOGNITION_PROBE_UNSAFE_OUTPUT');
  }
  const visit = (value) => {
    if (Array.isArray(value)) {
      value.forEach(visit);
      return;
    }
    if (!value || typeof value !== 'object') return;
    for (const [key, member] of Object.entries(value)) {
      if (FORBIDDEN_RECORD_KEYS.has(key)) throw new Error('DSH_RECOGNITION_PROBE_UNSAFE_OUTPUT');
      visit(member);
    }
  };
  visit(records);
}

function parseJsonLines(value) {
  return value.split(/\r?\n/u).filter(Boolean).map((line) => JSON.parse(line));
}

function spawnProbe({ cliPath, patchPath, outputPath, runDirectory, timeoutMs }) {
  return new Promise((resolvePromise, reject) => {
    const child = spawn(process.execPath, [
      cliPath,
      '--profile', 'headless',
      '--patch', patchPath,
      'Reply with exactly HOST_RUNTIME_OK after the adapter probe completes.',
    ], {
      cwd: runDirectory,
      env: { ...process.env, VECTORAI_DSH_RECOGNITION_PROBE_OUTPUT: outputPath },
      stdio: 'ignore',
    });
    let timedOut = false;
    const timer = setTimeout(() => {
      timedOut = true;
      child.kill('SIGTERM');
    }, timeoutMs);
    child.once('error', (error) => {
      clearTimeout(timer);
      reject(error);
    });
    child.once('close', (code) => {
      clearTimeout(timer);
      resolvePromise({ code, timedOut });
    });
  });
}

const invokedPath = process.argv[1] === undefined ? undefined : pathToFileURL(resolve(process.argv[1])).href;
if (invokedPath === import.meta.url) {
  runDshRecognitionProbe()
    .then((summary) => process.stdout.write(formatProbeSummary(summary)))
    .catch((error) => {
      const message = error instanceof Error ? error.message : String(error);
      process.stderr.write(`recognition probe: fail (${message})\n`);
      process.exitCode = 1;
    });
}
